// Writes templates.generated.ts: one require() per template and component screen of the spec (<spec>/fixtures/templates and components),
// so the sample app can present any of them by name without a server (the template sweep).
//   node tool/gen-templates.js            the spec is ../.spec (scripts/fetch-spec.sh) or $MINIWALL_SPEC_DIR
// The open spec has a small set of templates; point MINIWALL_SPEC_DIR at a folder with more to sweep a bigger library.
const fs = require('fs');
const path = require('path');

const exampleDir = path.resolve(__dirname, '..');

function specDir() {
  const dir = process.env.MINIWALL_SPEC_DIR ? path.resolve(process.env.MINIWALL_SPEC_DIR) : path.resolve(exampleDir, '../.spec');
  if (!fs.existsSync(path.join(dir, 'fixtures', 'templates'))) throw new Error(`The Miniwall spec is not at ${dir}: run scripts/fetch-spec.sh (or set MINIWALL_SPEC_DIR)`);
  return dir;
}

/** Writes example/templates.generated.ts from the spec and returns how many screens it lists. */
function generate(dir = specDir()) {
  const lines = [];
  for (const folder of ['templates', 'components']) {
    for (const file of fs.readdirSync(path.join(dir, 'fixtures', folder)).filter((f) => f.endsWith('.json')).sort()) {
      const name = file.replace(/\.json$/, '');
      const rel = path.relative(exampleDir, path.join(dir, 'fixtures', folder, file)).split(path.sep).join('/');
      lines.push(`  ${JSON.stringify(name)}: require(${JSON.stringify(rel)}),`);
    }
  }
  const out = `// Generated by tool/gen-templates.js from the Miniwall spec. Do not edit.
/* eslint-disable */
export const bundledTemplates: Record<string, any> = {
${lines.join('\n')}
};
`;
  fs.writeFileSync(path.join(exampleDir, 'templates.generated.ts'), out);
  return lines.length;
}

module.exports = { generate, specDir };

if (require.main === module) console.log(`wrote ${generate()} templates`);
